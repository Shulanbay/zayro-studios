-- Marketing hub: landing pages (block builder + per-page tracking code), the
-- lead CRM with attribution, global tracking settings, manually entered ad
-- spend (for CPL / CPA / ROAS) and a saved UTM-link library.
-- Additive and idempotent: new tables, one new system role, two permissions
-- added to Studio Manager. No existing data is changed.
--
-- Access control is enforced by the application server (roles + permissions
-- checked on every page and API route); the database is never exposed to
-- browsers, so there is no client-side row-level security to configure.

CREATE TABLE IF NOT EXISTS "landing_pages" (
  "id" uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "slug" varchar(80) NOT NULL,
  "title" varchar(200) NOT NULL,
  "meta_description" varchar(320),
  "og_image_url" varchar(500),
  "noindex" boolean NOT NULL DEFAULT false,
  "is_published" boolean NOT NULL DEFAULT false,
  "content_blocks" jsonb NOT NULL DEFAULT '[]'::jsonb,
  "head_scripts" text,
  "body_scripts" text,
  "scripts_consent" varchar(20) NOT NULL DEFAULT 'advertising',
  "published_at" timestamp with time zone,
  "created_by" varchar(255),
  "updated_by" varchar(255),
  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT "landing_pages_slug_unique" UNIQUE ("slug"),
  CONSTRAINT "landing_pages_slug_check" CHECK ("slug" ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  CONSTRAINT "landing_pages_consent_check" CHECK ("scripts_consent" IN ('necessary', 'analytics', 'advertising'))
);--> statement-breakpoint

CREATE TABLE IF NOT EXISTS "leads" (
  "id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY (START WITH 1001),
  "created_at" timestamp with time zone NOT NULL DEFAULT now(),
  "updated_at" timestamp with time zone NOT NULL DEFAULT now(),
  "name" varchar(200),
  "phone" varchar(40),
  "email" varchar(255),
  "message" text,
  "contact_method" varchar(20) NOT NULL DEFAULT 'form',
  "landing_page_slug" varchar(80),
  "landing_path" varchar(300),
  "referrer" varchar(500),
  "utm_source" varchar(150),
  "utm_medium" varchar(150),
  "utm_campaign" varchar(150),
  "utm_content" varchar(150),
  "utm_term" varchar(150),
  "utm_id" varchar(150),
  "platform" varchar(30) NOT NULL DEFAULT 'direct',
  -- Ad click IDs (gclid, fbclid, ttclid, rdt_cid, epik, twclid, custom): stored only with
  -- advertising consent, AES-GCM encrypted (the same key as analytics click IDs).
  "click_id_types" varchar(150),
  "click_ids_encrypted" text,
  "status" varchar(20) NOT NULL DEFAULT 'new',
  "revenue_cents" integer NOT NULL DEFAULT 0,
  "ad_spend_attributed_cents" integer NOT NULL DEFAULT 0,
  "notes" text,
  "lost_reason" varchar(200),
  "assigned_to" varchar(255),
  "customer_id" uuid REFERENCES "customers" ("id") ON DELETE SET NULL,
  "analytics_session_id" uuid REFERENCES "analytics_sessions" ("id") ON DELETE SET NULL,
  "status_changed_at" timestamp with time zone NOT NULL DEFAULT now(),
  "created_by" varchar(255),
  CONSTRAINT "leads_contact_method_check" CHECK ("contact_method" IN ('form', 'whatsapp', 'telegram', 'direct_booking', 'phone', 'email', 'instagram', 'other')),
  CONSTRAINT "leads_status_check" CHECK ("status" IN ('new', 'in_progress', 'booked', 'paid', 'rejected')),
  CONSTRAINT "leads_money_check" CHECK ("revenue_cents" >= 0 AND "ad_spend_attributed_cents" >= 0)
);--> statement-breakpoint
