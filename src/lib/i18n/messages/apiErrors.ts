/** An API message in the admin's language, or the original English text when it isn't translated. */
export function translateApiMessage(locale: AdminLocale, message: string | null | undefined): string {
  if (!message) return '';
  if (locale === 'en') return message;
  return API_MESSAGES[locale][message] ?? message;
}
